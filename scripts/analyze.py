"""Score the pre-registered hypotheses H1-H4 from results/*.json and write docs/results.md.

Decision rules: docs/PROJECT_PLAN.md section 4 (disclosed deviation in docs/PREREGISTRATION.md).
Re-running on the same result files produces an identical docs/results.md.
"""

import json
from pathlib import Path

from labelsweep.report import summarize, summary_table

ROOT = Path(__file__).resolve().parents[1]
SIZES = ["small", "medium", "large"]


def main() -> None:
    results = [
        json.loads(p.read_text(encoding="utf-8"))
        for p in sorted((ROOT / "results").glob("*.json"))
    ]
    rows = []
    for r in results:
        sm = summarize(r)
        td, tb = r["test"]["default"]["micro_f1"], r["test"]["best"]["micro_f1"]
        dd, db = r["dev"]["default"]["micro_f1"], r["dev"]["best"]["micro_f1"]
        lo, hi = r["test_gain_ci95"]
        size = next(s for s in SIZES if s in r["meta"]["model"])
        rows.append(
            dict(
                data=r["meta"]["data"],
                size=size,
                spread=sm["median_spread"],
                trivial=sm["median_trivial_spread"],
                test_gain=tb - td,
                dev_gain=db - dd,
                lo=lo,
                hi=hi,
            )
        )
    n = len(rows)
    datasets = sorted({x["data"] for x in rows})

    h1 = sum(x["spread"] >= 0.05 for x in rows)
    h2 = sum(x["test_gain"] < x["dev_gain"] and x["lo"] <= 0 <= x["hi"] for x in rows)
    h2_less = sum(x["test_gain"] < x["dev_gain"] for x in rows)
    h2_ci0 = sum(x["lo"] <= 0 <= x["hi"] for x in rows)
    h2_neg = sum(x["hi"] < 0 for x in rows)
    h2_pos = sum(x["lo"] > 0 for x in rows)
    order = {}
    for d in datasets:
        sp = {x["size"]: x["spread"] for x in rows if x["data"] == d}
        order[d] = sp
    h3 = sum(sp["small"] > sp["medium"] > sp["large"] for sp in order.values())
    h4 = sum(x["trivial"] >= 0.02 for x in rows)

    def pct(v):
        return f"{100 * v:.1f}"

    def verdict(ok):
        return "**supported**" if ok else "**not supported**"

    spreads = sorted(x["spread"] for x in rows)
    triv = sorted(x["trivial"] for x in rows)
    lines = [
        "# Results: label-wording sensitivity of zero-shot NER",
        "",
        f"Generated by `scripts/analyze.py` from {n} result files in `results/`. Types with fewer than 30 test",
        "spans are excluded from the aggregates. All F1 values are percentages; spreads and gains are F1 points.",
        "",
        "## Hypotheses",
        "",
        "| ID | Rule | Observed | Verdict |",
        "|---|---|---|---|",
        f"| H1 | median per-type spread >= 5 in all {n} runs | {h1}/{n} runs; range {pct(spreads[0])}-{pct(spreads[-1])} | {verdict(h1 == n)} |",
        f"| H2 | test gain < dev gain and 95% CI includes 0, in >= 10/{n} runs | {h2}/{n} (test < dev: {h2_less}/{n}; CI includes 0: {h2_ci0}/{n}; CI above 0: {h2_pos}/{n}; CI below 0: {h2_neg}/{n}) | {verdict(h2 >= 10)} |",
        f"| H3 | spread small > medium > large on >= 4/{len(datasets)} datasets | {h3}/{len(datasets)} datasets | {verdict(h3 >= 4)} |",
        f"| H4 | casing/plural spread >= 2 in >= 15/{n} runs | {h4}/{n} runs; range {pct(triv[0])}-{pct(triv[-1])} | {verdict(h4 >= 15)} |",
        "",
        "## Model size (H3): median per-type spread",
        "",
        "| dataset | small | medium | large |",
        "|---|---|---|---|",
    ]
    for d, sp in order.items():
        lines.append(
            f"| {d} | {pct(sp['small'])} | {pct(sp['medium'])} | {pct(sp['large'])} |"
        )
    lines += ["", "## All runs", "", summary_table(results)]
    out = ROOT / "docs" / "results.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(out.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
